// Builds src/lib/unit-art-map.ts — one picture per unit, keyed by unit slug —
// from scripts/unit-art/picks.json ({ slug: "words/pancho-tired" }); the scored picks
// with notes live in .course-work/unit-art/picks.json.
// Run: node scripts/unit-art/build-map.mjs
import fs from 'node:fs';

const picks = JSON.parse(fs.readFileSync('scripts/unit-art/picks.json', 'utf8'));
const files = [...new Set(Object.values(picks))].sort();
for (const f of files) {
  if (!fs.existsSync(`assets/images/${f}.webp`)) throw new Error(`missing assets/images/${f}.webp`);
}
const id = new Map(files.map((f, i) => [f, `a${i}`]));
const out = [
  '// Generated by scripts/unit-art/build-map.mjs — do not edit by hand.',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  ...files.map((f) => `const ${id.get(f)} = require('@/assets/images/${f}.webp');`),
  '',
  '/** The picture for each unit, by unit slug. */',
  'export const unitArtMap: Record<string, ImageSourcePropType> = {',
  ...Object.entries(picks)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slug, p]) => `  '${slug}': ${id.get(p)},`),
  '};',
  '',
];
fs.writeFileSync('src/lib/unit-art-map.ts', out.join('\n'));
console.log(`${Object.keys(picks).length} units, ${files.length} pictures`);
