// Writes src/lib/word-art-map.ts: which picture each taught word shows on its
// "new word" card. Course words are keyed by lemma id, Argentine pack words by
// their Spanish ("pack:bondi"). A word whose thing already has culture art
// reuses that figure; the rest point at assets/images/words/<concept>.webp,
// cut from Gemini sticker sheets by scripts/word-art/cut-grid.py.
//
//   node scripts/word-art/build-map.mjs
//
// Input: .course-work/word-art/word-concepts.json ({ key: { es, concept, reuse } }).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const words = JSON.parse(fs.readFileSync(path.join(root, '.course-work/word-art/word-concepts.json'), 'utf8'));

const files = new Map(); // require path → variable name
const course = [];
const packs = [];
const missing = [];
for (const [key, w] of Object.entries(words)) {
  const rel = w.reuse ? `objects/${w.reuse}-figure.webp` : `words/${w.concept}.webp`;
  if (!fs.existsSync(path.join(root, 'assets/images', rel))) {
    missing.push(`${w.es} → ${rel}`);
    continue;
  }
  if (!files.has(rel)) files.set(rel, `a${files.size}`);
  const row = `  ${JSON.stringify(key.replace(/^pack:/, ''))}: ${files.get(rel)},`;
  (key.startsWith('pack:') ? packs : course).push(row);
}

const out = `// Generated by scripts/word-art/build-map.mjs — do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

${[...files].map(([rel, v]) => `const ${v} = require('@/assets/images/${rel}');`).join('\n')}

/** Course words, by lemma id. */
export const courseWordArt: Record<string, ImageSourcePropType> = {
${course.join('\n')}
};

/** Argentine pack words, by their Spanish. */
export const packWordArt: Record<string, ImageSourcePropType> = {
${packs.join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'src/lib/word-art-map.ts'), out);
console.log(`${course.length} course words, ${packs.length} pack words, ${files.size} images`);
if (missing.length) console.log(`missing (${missing.length}):\n  ${missing.join('\n  ')}`);
