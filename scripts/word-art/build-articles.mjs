// Writes src/lib/noun-articles.ts: the indefinite article each pictured noun
// is taught with on its "new word" screen ("un paquete", "una medialuna",
// "unos anteojos"), so its gender comes with it.
//
//   node scripts/word-art/build-articles.mjs
//
// Input: .course-work/word-art/noun-genders.json ({ lemma_id: { lemma, gender,
// un, plural_only, skip, note } }), tagged for the nouns of word-art-map.ts.
// Left out: skipped nouns (nobody says "un fútbol"), and nouns for either sex
// (turista, estudiante): "un turista" would say she is a man.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const nouns = JSON.parse(fs.readFileSync(path.join(root, '.course-work/word-art/noun-genders.json'), 'utf8'));
const EITHER = /both genders|either gender|common gender|ambos géneros|los dos géneros/i;

const rows = Object.entries(nouns)
  .filter(([, n]) => !n.skip && !EITHER.test(n.note ?? ''))
  .sort(([, a], [, b]) => a.lemma.localeCompare(b.lemma, 'es'))
  .map(([id, n]) => {
    // "un agua": a feminine noun with a stressed a takes un, and unas in the plural.
    const one = n.gender === 'f' && n.un !== 'un' ? 'una' : 'un';
    const parts = [`one: '${one}'`];
    if (n.gender === 'f' && one === 'un') parts.push('feminine: true');
    if (n.plural_only) parts.push('many: true');
    return `  '${id}': { ${parts.join(', ')} }, // ${n.lemma}`;
  });

const out = `// Generated by scripts/word-art/build-articles.mjs — do not edit by hand.
export const nounArticle: Record<string, { one: 'un' | 'una'; feminine?: true; many?: true }> = {
${rows.join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'src/lib/noun-articles.ts'), out);
console.log(`${rows.length} nouns`);
